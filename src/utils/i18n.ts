export function getTranslation(lang: LanguageCode, key: keyof typeof TRANSLATIONS.en): string {
  const dict = TRANSLATIONS[lang] || TRANSLATIONS.en;
  return dict[key] || TRANSLATIONS.en[key] || key;
}

export function translateDifficulty(lang: LanguageCode, difficulty: string): string {
  if (!difficulty) return '';
  const match = difficulty.match(/\d+/);
  if (match) {
    const num = parseInt(match[0], 10);
    if (num >= 1 && num <= 6) {
      if (lang === 'zh') {
        const chineseNums = ['', '一', '二', '三', '四', '五', '六'];
        return `${chineseNums[num]}年级`;
      }
      if (lang === 'ms') {
        return `Tahun ${num}`;
      }
      return `Year ${num}`;
    }
  }
  // Fallback to legacy or raw difficulty values
  if (difficulty === 'Beginner') return lang === 'zh' ? '初级' : lang === 'ms' ? 'Pemula' : 'Beginner';
  if (difficulty === 'Intermediate') return lang === 'zh' ? '中级' : lang === 'ms' ? 'Pertengahan' : 'Intermediate';
  if (difficulty === 'Master') return lang === 'zh' ? '高级' : lang === 'ms' ? 'Mahir' : 'Master';
  return difficulty;
}